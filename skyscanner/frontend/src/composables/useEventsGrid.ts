/**
 * The composable that binds the generated inventory table to the API and to the actions of the toolbar.
 */

import { createGridController, type GridController, type RowsQuery } from '@truth-platform/ag-grid-ts'
import { language, localiseColumns } from '@truth-platform/core-ui'
import { watch, type Ref } from 'vue'

import type { ParseState } from '@/models/common'
import type { GeneratedGridConfiguration, GridRow, GridRowsPage } from '@/models/grid'
import type { EventExportRequest, FilterCondition, GridRowsRequest } from '@/models/query'
import type { EventType } from '@/models/event'
import { readEventColumns, readEventRows } from '@/requests/grid'
import { listEventTypes } from '@/requests/schema'
import { withLocalDays } from '@/utils/day-filters'
import { askedFieldKeys } from '@/utils/event-fields'

const DEFAULT_PAGE_SIZE = 25
const EXPORT_PAGE_SIZE = 500

/*
 * Columns the service still generates that the inventory does not show. The values behind them are stored and
 * served exactly as before - when an event last changed is still on its own page - they are only kept out of
 * the table, its column picker and everything else that reads the table's columns.
 */
const HIDDEN_COLUMNS: ReadonlySet<string> = new Set(['updated_at'])

/**
 * Drop the columns the inventory does not show from a configuration the service generated.
 */
const withoutHiddenColumns = (configuration: GeneratedGridConfiguration): GeneratedGridConfiguration => ({
  ...configuration,
  columns: configuration.columns.filter((column) => !HIDDEN_COLUMNS.has(column.colId)),
})

/**
 * Hide the columns of the declared fields that are bound to event types.
 *
 * Such a field is asked for on the events of its types only, so its column would stand empty on every other
 * row. It is therefore offered in the column picker rather than shown, whatever its declaration says.
 */
const withTypeBoundColumnsHidden = (
  configuration: GeneratedGridConfiguration,
  types: EventType[],
): GeneratedGridConfiguration => {
  const bound = askedFieldKeys(types)

  return {
    ...configuration,
    columns: configuration.columns.map((column) =>
      column.dynamic && bound.has(column.colId) ? { ...column, hide: true } : column,
    ),
  }
}

/** What the table is narrowed by on top of its own column filters. */
interface EventsGridInput {
  /** The industries picked in the tabs; none picked is every industry. */
  industries: Ref<string[]>
  /**
   * Conditions that belong to no column of the table - a field of the entities inside an event, or an event
   * field somebody filtered by from the filter dialog. They travel with every request beside the column ones.
   */
  fieldFilters: Ref<FilterCondition[]>
}

/**
 * Turn the query of the grid controller into the request payload the backend expects.
 */
const toRowsRequest = (query: RowsQuery, input: EventsGridInput): GridRowsRequest => ({
  search: query.search,
  industry: null,
  industries: [...input.industries.value],
  parse_state: query.parseState as ParseState,
  filters: withLocalDays([...query.filters, ...input.fieldFilters.value]),
  sort: query.sort,
  page: query.page,
  page_size: query.pageSize,
  columns: [],
})

/**
 * Build the controller of the inventory table, already wired to the endpoints of the events service.
 */
const useEventsGrid = (input: EventsGridInput): GridController => {
  const controller = createGridController({
    /*
     * The columns are generated by the service, headers and all, and each of them arrives carrying both the
     * name it is known by and the Hebrew name somebody wrote down for it. Which of the two ends up on screen
     * is decided once, here, because everything downstream - the grid, the chips, the pills, the column
     * picker, the viewer a long value opens - reads the one header this leaves behind.
     */
    loadConfiguration: async (): Promise<GeneratedGridConfiguration> => {
      const [configuration, types] = await Promise.all([readEventColumns(input.industries.value), listEventTypes(null)])

      return localiseColumns(withTypeBoundColumnsHidden(withoutHiddenColumns(configuration), types))
    },
    loadRows: (query): Promise<GridRowsPage> => readEventRows(toRowsRequest(query, input)),
    pageSize: DEFAULT_PAGE_SIZE,
  })

  /*
   * A change of language changes every header at once, which is the same rebuild a change of declarations
   * is - the columns are not what they were. It costs one reading of the configuration and leaves the rows
   * exactly where they are, because nothing about which rows are on screen has changed.
   */
  watch(language, () => {
    void controller.refreshConfiguration()
  })

  return controller
}

/**
 * Build the request payload of the current view, used by the export action of the toolbar.
 *
 * The export follows the table as it stands on screen, so it carries the very filters and ordering the grid
 * is showing. Handing it a list of identifiers narrows it further, down to the rows the user ticked.
 */
const buildExportRequest = (
  controller: GridController,
  input: EventsGridInput,
  columns: string[],
  eventIds: string[] = [],
): EventExportRequest => ({
  search: controller.search.value.length > 0 ? controller.search.value : null,
  industry: null,
  industries: [...input.industries.value],
  parse_state: controller.parseState.value as ParseState,
  filters: withLocalDays([...controller.filterConditions.value, ...input.fieldFilters.value]),
  sort: controller.sortSpecifications.value,
  page: 1,
  page_size: EXPORT_PAGE_SIZE,
  columns,
  event_ids: eventIds,
})

/**
 * Find one row of the current block by its identifier.
 */
const findRowById = (rows: GridRow[], rowId: string): GridRow | undefined =>
  rows.find((row) => String(row.id) === rowId)

export type { EventsGridInput }
export { DEFAULT_PAGE_SIZE, buildExportRequest, findRowById, toRowsRequest, useEventsGrid }
